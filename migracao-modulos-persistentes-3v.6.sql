-- ADHONEP-SC 3v.6 — módulos persistentes
-- Idempotente: cria tabelas e políticas dos módulos sem apagar dados existentes.
-- Aplicar no SQL Editor do Supabase. Testar primeiro em ambiente de homologação.
-- Pressupõe public.is_state_admin() existente e validada.

begin;

create table if not exists public.speakers (
  id bigint generated by default as identity primary key,
  full_name text not null check (length(trim(full_name)) between 2 and 180),
  profession text,
  chapter_name text,
  testimony_type text not null default 'Capítulo',
  status text not null default 'Ativo' check (status in ('Ativo','Inativo')),
  phone_private text,
  biography text,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chapter_reports (
  id bigint generated by default as identity primary key,
  event_id bigint references public.events(id) on delete set null,
  chapter_id bigint not null references public.chapters(id) on delete restrict,
  event_name text not null,
  report_kind text not null default 'Andamento mensal',
  responsible_name text not null,
  attendee_count integer check (attendee_count is null or attendee_count >= 0),
  summary text not null,
  notes text,
  status text not null default 'Entregue' check (status in ('Rascunho','Entregue','Em revisão','Correções solicitadas','Reenviado','Aprovado','Encaminhado à sede')),
  submitted_at timestamptz,
  reviewer_notes text,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.statewide_announcements (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) between 3 and 180),
  category text not null default 'Institucional',
  priority text not null default 'normal' check (priority in ('normal','important','urgent')),
  summary text not null,
  body text not null,
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  action_label text,
  action_url text,
  show_popup boolean not null default false,
  status text not null default 'draft' check (status in ('draft','pending','changes','approved','published','archived')),
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  submitted_at timestamptz,
  decision_by uuid references auth.users(id) on delete set null,
  decided_at timestamptz,
  feedback text,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at is null or ends_at >= starts_at),
  check (action_url is null or action_url ~ '^https?://')
);

create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid default auth.uid() references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  summary text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists speakers_name_idx on public.speakers (full_name);
create index if not exists speakers_status_idx on public.speakers (status);
create index if not exists chapter_reports_chapter_created_idx on public.chapter_reports (chapter_id, created_at desc);
create index if not exists chapter_reports_status_idx on public.chapter_reports (status, created_at desc);
create index if not exists announcements_public_idx on public.statewide_announcements (status, starts_at, ends_at);
create index if not exists audit_created_idx on public.admin_audit_log (created_at desc);

create or replace function public.set_adhonep_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end; $$;
revoke all on function public.set_adhonep_updated_at() from public, anon, authenticated;
drop trigger if exists speakers_updated_at on public.speakers;
create trigger speakers_updated_at before update on public.speakers for each row execute function public.set_adhonep_updated_at();
drop trigger if exists chapter_reports_updated_at on public.chapter_reports;
create trigger chapter_reports_updated_at before update on public.chapter_reports for each row execute function public.set_adhonep_updated_at();
drop trigger if exists announcements_updated_at on public.statewide_announcements;
create trigger announcements_updated_at before update on public.statewide_announcements for each row execute function public.set_adhonep_updated_at();

alter table public.speakers enable row level security;
alter table public.chapter_reports enable row level security;
alter table public.statewide_announcements enable row level security;
alter table public.admin_audit_log enable row level security;

-- Remove apenas políticas com estes nomes, para permitir reexecução idempotente.
drop policy if exists speakers_admin_all on public.speakers;
create policy speakers_admin_all on public.speakers for all to authenticated
  using (public.is_state_admin()) with check (public.is_state_admin() and (created_by is null or created_by = auth.uid()));

drop policy if exists chapter_reports_admin_all on public.chapter_reports;
create policy chapter_reports_admin_all on public.chapter_reports for all to authenticated
  using (public.is_state_admin()) with check (public.is_state_admin() and (created_by is null or created_by = auth.uid()));

drop policy if exists announcements_public_read on public.statewide_announcements;
create policy announcements_public_read on public.statewide_announcements for select to anon, authenticated
  using (status = 'published' and starts_at <= now() and (ends_at is null or ends_at >= now()));
drop policy if exists announcements_admin_all on public.statewide_announcements;
create policy announcements_admin_all on public.statewide_announcements for all to authenticated
  using (public.is_state_admin()) with check (public.is_state_admin());

drop policy if exists audit_admin_select on public.admin_audit_log;
create policy audit_admin_select on public.admin_audit_log for select to authenticated
  using (public.is_state_admin());
drop policy if exists audit_admin_insert on public.admin_audit_log;
create policy audit_admin_insert on public.admin_audit_log for insert to authenticated
  with check (public.is_state_admin() and (actor_id is null or actor_id = auth.uid()));

revoke all on public.speakers, public.chapter_reports, public.statewide_announcements, public.admin_audit_log from anon, authenticated;
grant select, insert, update, delete on public.speakers, public.chapter_reports, public.statewide_announcements to authenticated;
grant select, insert on public.admin_audit_log to authenticated;
grant select on public.statewide_announcements to anon;
grant usage, select on sequence public.speakers_id_seq, public.chapter_reports_id_seq, public.statewide_announcements_id_seq, public.admin_audit_log_id_seq to authenticated;

commit;

-- Pós-execução: deve retornar quatro tabelas com RLS habilitado.
select c.relname as tabela, c.relrowsecurity as rls_habilitado
from pg_class c join pg_namespace n on n.oid=c.relnamespace
where n.nspname='public' and c.relname in ('speakers','chapter_reports','statewide_announcements','admin_audit_log')
order by c.relname;
