-- ADHONEP-SC · gera, a partir do banco de PRODUÇÃO, o SQL da estrutura (sem nenhum dado).
-- Só LÊ o catálogo do Postgres. Resultado: supabase/esquema/00-base.sql
-- Usado quando o esquema muda fora das migrações (ex.: SQL Editor). Rodar: ver testes/LEIA-ME.md.
SET search_path = '';  -- nomes saem completos (public.x), independentes do search_path de quem carrega
with
sq as (  -- sequências comuns (as de IDENTITY nascem com a coluna)
  select string_agg('CREATE SEQUENCE ' || s.seqrelid::regclass::text || ' AS ' || format_type(s.seqtypid, null) || ' START ' || s.seqstart || ' INCREMENT ' || s.seqincrement || ' MINVALUE ' || s.seqmin || ' MAXVALUE ' || s.seqmax || case when s.seqcycle then ' CYCLE' else '' end || ';', E'\n' order by 1) t,
         string_agg((select 'ALTER SEQUENCE ' || s.seqrelid::regclass::text || ' OWNED BY ' || d.refobjid::regclass::text || '.' || quote_ident(a.attname) || ';' from pg_depend d join pg_attribute a on a.attrelid=d.refobjid and a.attnum=d.refobjsubid where d.objid=s.seqrelid and d.deptype='a' limit 1), E'\n') own
  from pg_sequence s join pg_class c on c.oid = s.seqrelid
  where c.relnamespace = 'public'::regnamespace
    and not exists (select 1 from pg_depend d where d.objid = s.seqrelid and d.deptype = 'i')
),
fn as (
  select string_agg(pg_get_functiondef(p.oid) || ';', E'\n\n' order by p.proname, p.oid) t
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind in ('f','p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
tb as (
  select string_agg(
    'CREATE TABLE public.' || quote_ident(c.relname) || E' (\n' ||
    (select string_agg('  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
        || case when a.attidentity = 'a' then ' GENERATED ALWAYS AS IDENTITY'
                when a.attidentity = 'd' then ' GENERATED BY DEFAULT AS IDENTITY'
                when a.attgenerated = 's' then ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
                when ad.adbin is not null then ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end
        || case when a.attnotnull then ' NOT NULL' else '' end, E',\n' order by a.attnum)
     from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
     where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped)
    || E'\n);', E'\n\n' order by c.relname) t
  from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind in ('r','p')
),
co as (
  select string_agg('ALTER TABLE ONLY public.' || quote_ident(r.relname) || ' ADD CONSTRAINT ' || quote_ident(k.conname) || ' ' || pg_get_constraintdef(k.oid) || ';',
                    E'\n' order by case k.contype when 'p' then 1 when 'u' then 2 when 'x' then 3 when 'c' then 4 else 5 end, r.relname, k.conname) t
  from pg_constraint k join pg_class r on r.oid = k.conrelid
  where r.relnamespace = 'public'::regnamespace and k.contype in ('p','u','c','f','x') and r.relkind in ('r','p')
),
ix as (
  select string_agg(i.indexdef || ';', E'\n' order by i.tablename, i.indexname) t
  from pg_indexes i
  where i.schemaname = 'public'
    and not exists (select 1 from pg_constraint k where k.conindid = (quote_ident(i.schemaname) || '.' || quote_ident(i.indexname))::regclass)
),
vw as (
  select string_agg('CREATE VIEW public.' || quote_ident(c.relname)
         || coalesce(' WITH (' || array_to_string(c.reloptions, ', ') || ')', '')
         || E' AS\n' || pg_get_viewdef(c.oid, true), E'\n\n' order by c.oid) t
  from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind = 'v'
),
tg as (
  select string_agg(pg_get_triggerdef(t.oid) || ';', E'\n' order by c.relname, t.tgname) t
  from pg_trigger t join pg_class c on c.oid = t.tgrelid
  where c.relnamespace = 'public'::regnamespace and not t.tgisinternal
),
rl as (
  select string_agg('ALTER TABLE public.' || quote_ident(c.relname) || ' ENABLE ROW LEVEL SECURITY;'
         || case when c.relforcerowsecurity then E'\nALTER TABLE public.' || quote_ident(c.relname) || ' FORCE ROW LEVEL SECURITY;' else '' end,
         E'\n' order by c.relname) t
  from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind in ('r','p') and c.relrowsecurity
),
po as (
  select string_agg('CREATE POLICY ' || quote_ident(p.polname) || ' ON public.' || quote_ident(c.relname)
      || ' AS ' || case when p.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end
      || ' FOR ' || case p.polcmd when 'r' then 'SELECT' when 'a' then 'INSERT' when 'w' then 'UPDATE' when 'd' then 'DELETE' else 'ALL' end
      || ' TO ' || coalesce((select string_agg(case when r = 0 then 'public' else quote_ident(r::regrole::text) end, ', ') from unnest(p.polroles) r), 'public')
      || coalesce(E'\n  USING (' || pg_get_expr(p.polqual, p.polrelid) || ')', '')
      || coalesce(E'\n  WITH CHECK (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')', '') || ';',
      E'\n' order by c.relname, p.polname) t
  from pg_policy p join pg_class c on c.oid = p.polrelid where c.relnamespace = 'public'::regnamespace
),
gr_t as (  -- privilégios de tabela/visão (MAINTAIN fica de fora: só existe no Postgres 17 e não é exposto pela API)
  select string_agg('GRANT ' || a.privilege_type || ' ON TABLE public.' || quote_ident(c.relname) || ' TO '
      || case when a.grantee = 0 then 'PUBLIC' else quote_ident(a.grantee::regrole::text) end || ';', E'\n' order by c.relname, a.grantee::regrole::text, a.privilege_type) t
  from pg_class c, aclexplode(c.relacl) a
  where c.relnamespace = 'public'::regnamespace and c.relkind in ('r','p','v','m')
    and a.privilege_type <> 'MAINTAIN'
    and (a.grantee = 0 or a.grantee::regrole::text in ('anon','authenticated','service_role'))
),
gr_c as (  -- privilégios por coluna
  select string_agg('GRANT ' || a.privilege_type || ' (' || quote_ident(at.attname) || ') ON TABLE public.' || quote_ident(c.relname) || ' TO '
      || case when a.grantee = 0 then 'PUBLIC' else quote_ident(a.grantee::regrole::text) end || ';', E'\n' order by c.relname, at.attnum, a.privilege_type) t
  from pg_class c join pg_attribute at on at.attrelid = c.oid and at.attnum > 0 and not at.attisdropped, aclexplode(at.attacl) a
  where c.relnamespace = 'public'::regnamespace and (a.grantee = 0 or a.grantee::regrole::text in ('anon','authenticated','service_role'))
),
gr_f as (  -- quem executa cada função (sem ACL = qualquer um)
  select string_agg(
      'REVOKE ALL ON FUNCTION ' || p.oid::regprocedure::text || ' FROM PUBLIC;' ||
      coalesce((select string_agg(E'\nGRANT EXECUTE ON FUNCTION ' || p.oid::regprocedure::text || ' TO '
                  || case when a.grantee = 0 then 'PUBLIC' else quote_ident(a.grantee::regrole::text) end || ';', '' order by a.grantee::regrole::text)
                from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
                where a.privilege_type = 'EXECUTE' and (a.grantee = 0 or a.grantee::regrole::text in ('anon','authenticated','service_role'))), ''),
      E'\n' order by p.proname, p.oid) t
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind in ('f','p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
gr_s as (
  select string_agg('GRANT ' || a.privilege_type || ' ON SEQUENCE public.' || quote_ident(c.relname) || ' TO '
      || case when a.grantee = 0 then 'PUBLIC' else quote_ident(a.grantee::regrole::text) end || ';', E'\n' order by c.relname, a.privilege_type) t
  from pg_class c, aclexplode(c.relacl) a
  where c.relnamespace = 'public'::regnamespace and c.relkind = 'S'
    and (a.grantee = 0 or a.grantee::regrole::text in ('anon','authenticated','service_role'))
)
select
  E'-- ADHONEP-SC · ESTRUTURA DO BANCO (sem dados) exportada da produção em ' || to_char(now() at time zone 'America/Sao_Paulo', 'DD/MM/YYYY HH24:MI') || E'\n'
  || E'-- Gerado por testes/banco/exportar-esquema.sql. Não editar à mão: mudanças novas entram em supabase/migracoes/.\n'
  || E'SET check_function_bodies = off;\nSET client_min_messages = warning;\n\n'
  || E'-- ===== SEQUÊNCIAS =====\n' || coalesce(sq.t, '') || E'\n\n'
  || E'-- ===== TABELAS =====\n' || coalesce(tb.t, '') || E'\n\n'
  || coalesce(sq.own, '') || E'\n\n'
  || E'-- ===== FUNÇÕES =====\n' || coalesce(fn.t, '') || E'\n\n'
  || E'-- ===== RESTRIÇÕES =====\n' || coalesce(co.t, '') || E'\n\n'
  || E'-- ===== ÍNDICES =====\n' || coalesce(ix.t, '') || E'\n\n'
  || E'-- ===== VISÕES =====\n' || coalesce(vw.t, '') || E'\n\n'
  || E'-- ===== GATILHOS =====\n' || coalesce(tg.t, '') || E'\n\n'
  || E'-- ===== RLS =====\n' || coalesce(rl.t, '') || E'\n\n'
  || E'-- ===== POLÍTICAS =====\n' || coalesce(po.t, '') || E'\n\n'
  || E'-- ===== PERMISSÕES =====\n'
  || E'REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC, anon, authenticated;\n'
  || E'REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM PUBLIC, anon, authenticated;\n'
  || coalesce(gr_t.t, '') || E'\n' || coalesce(gr_c.t, '') || E'\n' || coalesce(gr_s.t, '') || E'\n\n'
  || coalesce(gr_f.t, '') || E'\n' as sql
from sq, fn, tb, co, ix, vw, tg, rl, po, gr_t, gr_c, gr_f, gr_s;
