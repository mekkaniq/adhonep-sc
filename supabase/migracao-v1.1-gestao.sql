begin;

-- ============================================================
-- 1) Mandatos (presidente do capítulo, diretor regional etc.)
--    Cada linha é de UM capítulo OU de UMA região.
-- ============================================================
create table if not exists public.leader_mandates (
  id          bigint generated by default as identity primary key,
  chapter_id  bigint references public.chapters(id) on delete cascade,
  region_id   bigint references public.regions(id) on delete cascade,
  role_label  text not null check (char_length(role_label) between 2 and 60),
  person_name text not null check (char_length(person_name) between 2 and 160),
  start_date  date,
  end_date    date not null,
  notes       text check (notes is null or char_length(notes) <= 500),
  created_at  timestamptz not null default now(),
  created_by  uuid default auth.uid() references auth.users(id) on delete set null,
  updated_at  timestamptz not null default now(),
  updated_by  uuid default auth.uid() references auth.users(id) on delete set null,
  check ((chapter_id is not null) <> (region_id is not null)),
  check (start_date is null or end_date >= start_date)
);
create index if not exists leader_mandates_chapter_idx on public.leader_mandates (chapter_id, end_date);
create index if not exists leader_mandates_region_idx on public.leader_mandates (region_id, end_date);

create or replace function public.adh_mandate_stamp() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then new.created_at := now(); new.created_by := auth.uid(); end if;
  new.updated_at := now(); new.updated_by := auth.uid();
  return new;
end $$;
revoke all on function public.adh_mandate_stamp() from public, anon, authenticated;
drop trigger if exists leader_mandates_stamp on public.leader_mandates;
create trigger leader_mandates_stamp before insert or update on public.leader_mandates
  for each row execute function public.adh_mandate_stamp();

alter table public.leader_mandates enable row level security;
drop policy if exists lm_select on public.leader_mandates;
drop policy if exists lm_insert on public.leader_mandates;
drop policy if exists lm_update on public.leader_mandates;
drop policy if exists lm_delete on public.leader_mandates;
-- ler: gestão estadual; diretor regional (capítulos da sua região e a própria região); presidente (do próprio capítulo)
create policy lm_select on public.leader_mandates for select to authenticated using (
  public.adh_is_state_manager()
  or (chapter_id is not null and (public.adh_is_regional_director_of(chapter_id) or public.adh_is_president_of(chapter_id)))
  or (region_id is not null and public.adh_is_regional_director_of_region(region_id)));
-- gravar: gestão estadual (tudo) e diretor regional (somente mandatos de capítulos da sua região)
create policy lm_insert on public.leader_mandates for insert to authenticated with check (
  public.adh_is_state_manager() or (chapter_id is not null and public.adh_is_regional_director_of(chapter_id)));
create policy lm_update on public.leader_mandates for update to authenticated
  using (public.adh_is_state_manager() or (chapter_id is not null and public.adh_is_regional_director_of(chapter_id)))
  with check (public.adh_is_state_manager() or (chapter_id is not null and public.adh_is_regional_director_of(chapter_id)));
create policy lm_delete on public.leader_mandates for delete to authenticated using (
  public.adh_is_state_manager() or (chapter_id is not null and public.adh_is_regional_director_of(chapter_id)));
revoke all on public.leader_mandates from anon;
grant select, insert, update, delete on public.leader_mandates to authenticated;
grant all on public.leader_mandates to service_role;

-- ============================================================
-- 2) Registro de reuniões do capítulo (uma linha por data)
-- ============================================================
create table if not exists public.chapter_meeting_log (
  id           bigint generated by default as identity primary key,
  chapter_id   bigint not null references public.chapters(id) on delete cascade,
  meeting_date date not null,
  held         boolean not null default true,            -- false = "não houve reunião nesta semana"
  attendance   integer check (attendance is null or attendance between 0 and 5000),
  visitors     integer check (visitors is null or visitors between 0 and 5000),
  notes        text check (notes is null or char_length(notes) <= 500),
  created_at   timestamptz not null default now(),
  created_by   uuid default auth.uid() references auth.users(id) on delete set null,
  updated_at   timestamptz not null default now(),
  updated_by   uuid default auth.uid() references auth.users(id) on delete set null,
  unique (chapter_id, meeting_date)
);
create index if not exists chapter_meeting_log_idx on public.chapter_meeting_log (chapter_id, meeting_date desc);

-- datas no futuro não valem; presidente só mexe nos últimos 60 dias (gestão estadual não tem limite de retroativo)
create or replace function public.adh_meeting_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.meeting_date > (now() at time zone 'America/Sao_Paulo')::date then
    raise exception 'A data da reunião não pode estar no futuro.' using errcode = '23514';
  end if;
  if not public.adh_is_state_manager()
     and new.meeting_date < (now() at time zone 'America/Sao_Paulo')::date - 60 then
    raise exception 'Só é possível registrar reuniões dos últimos 60 dias. Fale com a diretoria estadual.' using errcode = '23514';
  end if;
  if tg_op = 'INSERT' then new.created_at := now(); new.created_by := auth.uid(); end if;
  new.updated_at := now(); new.updated_by := auth.uid();
  return new;
end $$;
revoke all on function public.adh_meeting_guard() from public, anon, authenticated;
drop trigger if exists chapter_meeting_log_guard on public.chapter_meeting_log;
create trigger chapter_meeting_log_guard before insert or update on public.chapter_meeting_log
  for each row execute function public.adh_meeting_guard();

alter table public.chapter_meeting_log enable row level security;
drop policy if exists cml_select on public.chapter_meeting_log;
drop policy if exists cml_insert on public.chapter_meeting_log;
drop policy if exists cml_update on public.chapter_meeting_log;
drop policy if exists cml_delete on public.chapter_meeting_log;
create policy cml_select on public.chapter_meeting_log for select to authenticated using (
  public.adh_is_state_manager() or public.adh_is_regional_director_of(chapter_id) or public.adh_is_president_of(chapter_id));
create policy cml_insert on public.chapter_meeting_log for insert to authenticated with check (
  public.adh_is_state_manager() or public.adh_is_president_of(chapter_id));
create policy cml_update on public.chapter_meeting_log for update to authenticated
  using (public.adh_is_state_manager() or public.adh_is_president_of(chapter_id))
  with check (public.adh_is_state_manager() or public.adh_is_president_of(chapter_id));
create policy cml_delete on public.chapter_meeting_log for delete to authenticated using (
  public.adh_is_state_manager() or public.adh_is_president_of(chapter_id));
revoke all on public.chapter_meeting_log from anon;
grant select, insert, update, delete on public.chapter_meeting_log to authenticated;
grant all on public.chapter_meeting_log to service_role;

commit;
