-- ADHONEP-SC · Relatório mensal do Apoio Jovem e do Apoio Feminino (mesmo modelo do Andamento mensal do capítulo)
-- Envia: coordenador daquele apoio no capítulo OU presidente do capítulo (ou administrador). Prazo: dia 5 do mês seguinte.
-- Aprova / pede correções: diretor regional do capítulo (ou administrador).
-- Vê: administrador, diretor estadual, diretor regional, presidente do capítulo e o coordenador DAQUELE apoio.
-- Seguro para rodar mais de uma vez.
begin;

create table if not exists public.chapter_support_reports (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references public.chapters(id) on delete restrict,
  kind text not null check (kind in ('youth','women')),
  ref_month date not null check (ref_month = date_trunc('month', ref_month)::date),
  meetings integer not null default 0 check (meetings between 0 and 40),
  avg_attendance integer check (avg_attendance is null or avg_attendance between 0 and 5000),
  new_participants integer not null default 0 check (new_participants between 0 and 5000),
  visitors integer not null default 0 check (visitors between 0 and 5000),
  visitors_notes text check (visitors_notes is null or length(visitors_notes) <= 1000),
  events_count integer not null default 0 check (events_count between 0 and 40),
  events_notes text check (events_notes is null or length(events_notes) <= 1500),
  highlights text check (highlights is null or length(highlights) <= 3000),
  support_requests text check (support_requests is null or length(support_requests) <= 2000),
  considerations text check (considerations is null or length(considerations) <= 3000),
  status text not null default 'Entregue' check (status in ('Entregue','Correções solicitadas','Reenviado','Aprovado')),
  submitted_at timestamptz,
  on_time boolean,
  reviewer_notes text,
  reviewed_by uuid,
  reviewed_at timestamptz,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (chapter_id, kind, ref_month)
);
create index if not exists csr_month_idx on public.chapter_support_reports (ref_month, kind, status);

drop trigger if exists csr_updated_at on public.chapter_support_reports;
create trigger csr_updated_at before update on public.chapter_support_reports
  for each row execute function public.set_adhonep_updated_at();

-- coordenador DAQUELE apoio neste capítulo
create or replace function public.adh_is_support_coord_of(p_chapter bigint, p_kind text)
returns boolean language sql stable security definer set search_path = '' as $$
  select p_chapter is not null and exists (select 1 from public.user_roles ur
    where ur.user_id = auth.uid() and ur.is_active and ur.chapter_id = p_chapter
      and ur.role = (p_kind || '_coordinator'))
$$;
revoke all on function public.adh_is_support_coord_of(bigint, text) from public, anon;
grant execute on function public.adh_is_support_coord_of(bigint, text) to authenticated;

create or replace function public.adh_can_submit_support(p_chapter bigint, p_kind text)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.is_state_admin() or public.adh_is_president_of(p_chapter) or public.adh_is_support_coord_of(p_chapter, p_kind)
$$;
revoke all on function public.adh_can_submit_support(bigint, text) from public, anon;
grant execute on function public.adh_can_submit_support(bigint, text) to authenticated;

create or replace function public.adh_can_see_support(p_chapter bigint, p_kind text)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.is_state_admin() or public.adh_has_role('state_director')
      or public.adh_is_regional_director_of(p_chapter)
      or public.adh_is_president_of(p_chapter)
      or public.adh_is_support_coord_of(p_chapter, p_kind)
$$;
revoke all on function public.adh_can_see_support(bigint, text) from public, anon;
grant execute on function public.adh_can_see_support(bigint, text) to authenticated;

-- Guarda de fluxo
create or replace function public.adh_guard_support_report()
returns trigger language plpgsql set search_path = '' as $$
declare v_deadline timestamptz;
begin
  if tg_op = 'INSERT' then
    if new.ref_month > date_trunc('month', now() at time zone 'America/Sao_Paulo')::date then
      raise exception 'Não é possível enviar relatório de um mês que ainda não começou.';
    end if;
    v_deadline := ((new.ref_month + interval '1 month')::date + 5)::timestamp at time zone 'America/Sao_Paulo';
    if public.is_state_admin() then
      new.submitted_at := coalesce(new.submitted_at, now());
      new.on_time := coalesce(new.on_time, now() < v_deadline);
      return new;
    end if;
    if public.adh_can_submit_support(new.chapter_id, new.kind) then
      new.status := 'Entregue';
      new.reviewer_notes := null; new.reviewed_by := null; new.reviewed_at := null;
      new.submitted_at := now();
      new.on_time := now() < v_deadline;
      new.created_by := auth.uid();
      return new;
    end if;
    raise exception 'Sem permissão para enviar relatório deste apoio.';
  end if;

  if new.chapter_id is distinct from old.chapter_id or new.ref_month is distinct from old.ref_month or new.kind is distinct from old.kind then
    raise exception 'Capítulo, apoio e mês de um relatório não podem ser alterados.';
  end if;
  if public.is_state_admin() then
    if new.status is distinct from old.status and new.status in ('Aprovado','Correções solicitadas') then
      new.reviewed_by := auth.uid(); new.reviewed_at := now();
    end if;
    return new;
  end if;

  if public.adh_is_regional_director_of(old.chapter_id) then
    if (to_jsonb(new) - 'status' - 'reviewer_notes' - 'reviewed_by' - 'reviewed_at' - 'updated_at')
       is distinct from (to_jsonb(old) - 'status' - 'reviewer_notes' - 'reviewed_by' - 'reviewed_at' - 'updated_at') then
      raise exception 'Diretor regional só pode alterar o status e as orientações da revisão.';
    end if;
    if not (old.status in ('Entregue','Reenviado') and new.status in ('Aprovado','Correções solicitadas')) then
      raise exception 'Transição de status não permitida: % -> %', old.status, new.status;
    end if;
    if new.status = 'Correções solicitadas' and length(trim(coalesce(new.reviewer_notes, ''))) < 3 then
      raise exception 'Informe as orientações ao solicitar correções.';
    end if;
    new.reviewed_by := auth.uid(); new.reviewed_at := now();
    return new;
  end if;

  if public.adh_can_submit_support(old.chapter_id, old.kind) then
    if old.status not in ('Entregue','Correções solicitadas') then
      raise exception 'Este relatório não pode mais ser editado (situação: %).', old.status;
    end if;
    if not ((old.status = 'Entregue' and new.status = 'Entregue')
         or (old.status = 'Correções solicitadas' and new.status in ('Correções solicitadas','Reenviado'))) then
      raise exception 'Transição de status não permitida: % -> %', old.status, new.status;
    end if;
    new.reviewer_notes := old.reviewer_notes; new.reviewed_by := old.reviewed_by; new.reviewed_at := old.reviewed_at;
    new.on_time := old.on_time;
    new.submitted_at := case when new.status = 'Reenviado' then now() else old.submitted_at end;
    return new;
  end if;
  raise exception 'Sem permissão para alterar este relatório.';
end; $$;
revoke all on function public.adh_guard_support_report() from public, anon, authenticated;

drop trigger if exists csr_guard on public.chapter_support_reports;
create trigger csr_guard before insert or update on public.chapter_support_reports
  for each row execute function public.adh_guard_support_report();

drop trigger if exists csr_audit on public.chapter_support_reports;
create trigger csr_audit after insert or update or delete on public.chapter_support_reports
  for each row execute function public.adh_audit_row();

alter table public.chapter_support_reports enable row level security;
drop policy if exists csr_select on public.chapter_support_reports;
drop policy if exists csr_insert on public.chapter_support_reports;
drop policy if exists csr_update on public.chapter_support_reports;
drop policy if exists csr_delete on public.chapter_support_reports;
create policy csr_select on public.chapter_support_reports for select to authenticated
  using (public.adh_can_see_support(chapter_id, kind));
create policy csr_insert on public.chapter_support_reports for insert to authenticated
  with check (public.adh_can_submit_support(chapter_id, kind));
create policy csr_update on public.chapter_support_reports for update to authenticated
  using (public.adh_can_see_support(chapter_id, kind))
  with check (public.adh_can_see_support(chapter_id, kind));
create policy csr_delete on public.chapter_support_reports for delete to authenticated
  using (public.is_state_admin());
revoke all on public.chapter_support_reports from anon;
grant select, insert, update, delete on public.chapter_support_reports to authenticated;

commit;
