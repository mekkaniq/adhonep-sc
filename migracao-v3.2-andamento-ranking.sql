-- ============================================================
-- 1) "Sócio" também pode ser solicitado no formulário público
--    (serve para enum OU check constraint de access_requests.requested_role)
-- ============================================================
do $$
declare t text; c record; nd text;
begin
  select udt_name || ':' || data_type into t from information_schema.columns
   where table_schema='public' and table_name='access_requests' and column_name='requested_role';
  if t is null then
    null;
  elsif t like '%:USER-DEFINED' then
    execute format('alter type public.%I add value if not exists %L', split_part(t, ':', 1), 'member');
  else
    for c in select conname, pg_get_constraintdef(oid) as def from pg_constraint
              where conrelid='public.access_requests'::regclass and contype='c'
                and pg_get_constraintdef(oid) like '%requested_role%' and pg_get_constraintdef(oid) not like '%member%' loop
      nd := replace(c.def, '''chapter_president''::text', '''chapter_president''::text, ''member''::text');
      if nd = c.def then nd := replace(c.def, '''chapter_president''', '''chapter_president'', ''member'''); end if;
      if nd <> c.def then
        execute format('alter table public.access_requests drop constraint %I', c.conname);
        execute format('alter table public.access_requests add constraint %I %s', c.conname, nd);
      end if;
    end loop;
  end if;
end $$;

-- ============================================================
-- 2) Histórico de situação dos capítulos (abertura, inativação, reativação)
--    Só registra mudanças A PARTIR de agora (o passado não tem data).
-- ============================================================
create table if not exists public.chapter_status_history (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null,
  old_status text,
  new_status text not null,
  changed_at timestamptz not null default now(),
  changed_by uuid default auth.uid()
);
create index if not exists chapter_status_history_idx on public.chapter_status_history (chapter_id, changed_at);

create or replace function public.adh_log_chapter_status()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_new text; v_old text;
begin
  v_new := coalesce(to_jsonb(new)->>'status', to_jsonb(new)->>'situation', to_jsonb(new)->>'situacao');
  if tg_op = 'INSERT' then
    if v_new is not null then
      insert into public.chapter_status_history(chapter_id, old_status, new_status) values (new.id, null, v_new);
    end if;
  else
    v_old := coalesce(to_jsonb(old)->>'status', to_jsonb(old)->>'situation', to_jsonb(old)->>'situacao');
    if v_new is not null and v_new is distinct from v_old then
      insert into public.chapter_status_history(chapter_id, old_status, new_status) values (new.id, v_old, v_new);
    end if;
  end if;
  return new;
end; $$;
revoke all on function public.adh_log_chapter_status() from public, anon, authenticated;

drop trigger if exists chapters_status_history on public.chapters;
create trigger chapters_status_history after insert or update on public.chapters
  for each row execute function public.adh_log_chapter_status();

alter table public.chapter_status_history enable row level security;
