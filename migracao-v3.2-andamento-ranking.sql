create table if not exists public.chapter_monthly_reports (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references public.chapters(id) on delete restrict,
  ref_month date not null check (ref_month = date_trunc('month', ref_month)::date),
  chapter_meetings integer not null default 0 check (chapter_meetings between 0 and 40),
  women_meetings integer not null default 0 check (women_meetings between 0 and 40),
  youth_meetings integer not null default 0 check (youth_meetings between 0 and 40),
  avg_attendance integer check (avg_attendance is null or avg_attendance between 0 and 5000),
  visitors integer not null default 0 check (visitors between 0 and 5000),
  visitors_notes text check (visitors_notes is null or length(visitors_notes) <= 1000),
  chapter_events integer not null default 0 check (chapter_events between 0 and 40),
  women_events integer not null default 0 check (women_events between 0 and 40),
  youth_events integer not null default 0 check (youth_events between 0 and 40),
  events_notes text check (events_notes is null or length(events_notes) <= 1500),
  prison_ministry_active boolean not null default false,
  prison_activities integer not null default 0 check (prison_activities between 0 and 200),
  considerations text check (considerations is null or length(considerations) <= 3000),
  status text not null default 'Entregue' check (status in ('Entregue','Correções solicitadas','Reenviado','Aprovado')),
  submitted_at timestamptz,
  on_time boolean,
  reviewer_notes text,
  reviewed_by uuid,
  reviewed_at timestamptz,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (chapter_id, ref_month)
);
create index if not exists cmr_month_idx on public.chapter_monthly_reports (ref_month, status);

